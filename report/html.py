"""
AutoRelay — HTML report renderer.

Takes a FindingsDocument and renders it as a self-contained, styled
HTML file. No external dependencies or CSS files required.
"""

from __future__ import annotations
import html
from .findings import FindingsDocument, Finding


def render_html(doc: FindingsDocument) -> str:
    """Render the findings document to a single self-contained HTML string."""
    
    # Start HTML structure and CSS
    parts = [
        "<!DOCTYPE html>",
        "<html lang='en'>",
        "<head>",
        "<meta charset='UTF-8'>",
        "<meta name='viewport' content='width=device-width, initial-scale=1.0'>",
        f"<title>AutoRelay Report — {html.escape(doc.target)}</title>",
        "<style>",
        _get_css(),
        "</style>",
        "</head>",
        "<body>",
        "<div class='container'>",
        
        # Header
        "<header>",
        f"<h1>NTLM Relay Preflight Assessment</h1>",
        f"<p class='meta'>Target: <code>{html.escape(doc.target)}</code> | Profile: {html.escape(doc.profile_name)} | Generated: {html.escape(doc.generated_at)}</p>",
        "</header>",

        # Executive Summary
        "<section class='summary'>",
        "<h2>Executive Summary</h2>",
        f"<p>{html.escape(doc.summary_text)}</p>",
        "<div class='stats'>",
        f"<div class='stat blocker'><span>{len(doc.blockers)}</span> Blockers</div>",
        f"<div class='stat warning'><span>{len(doc.warnings)}</span> Warnings</div>",
        f"<div class='stat unknown'><span>{len(doc.unknowns)}</span> Unknowns</div>",
        f"<div class='stat info'><span>{len(doc.info)}</span> Passed</div>",
        "</div>",
        "</section>",
    ]

    # Blockers
    if doc.blockers:
        parts.append("<section>")
        parts.append("<h2 class='text-blocker'>Critical Blockers</h2>")
        parts.append("<p>The following findings actively prevent the NTLM relay attack from succeeding:</p>")
        for finding in doc.blockers:
            parts.append(_render_finding(finding, "blocker"))
        parts.append("</section>")

    # Warnings
    if doc.warnings:
        parts.append("<section>")
        parts.append("<h2 class='text-warning'>Warnings</h2>")
        for finding in doc.warnings:
            parts.append(_render_finding(finding, "warning"))
        parts.append("</section>")

    # Unknowns
    if doc.unknowns:
        parts.append("<section>")
        parts.append("<h2 class='text-unknown'>Inconclusive Findings</h2>")
        parts.append("<p>The tool could not determine the state of the following checks. This is common on hardened systems.</p>")
        for finding in doc.unknowns:
            parts.append(_render_finding(finding, "unknown"))
        parts.append("</section>")

    # Info / Passed
    if doc.info:
        parts.append("<section>")
        parts.append("<h2 class='text-info'>Passed Checks</h2>")
        for finding in doc.info:
            parts.append(_render_finding(finding, "info", show_remediation=False))
        parts.append("</section>")

    # Footer
    parts.extend([
        "<footer>",
        "<p>Report generated by AutoRelay. For authorized security assessment only.</p>",
        "</footer>",
        "</div>",
        "</body>",
        "</html>"
    ])

    return "\n".join(parts)


def _render_finding(finding: Finding, severity_class: str, show_remediation: bool = True) -> str:
    check = finding.check
    
    # Format evidence nicely
    evidence_html = ""
    if check.evidence:
        evidence_html = "<div class='evidence'><h4>Evidence</h4><ul>"
        for k, v in check.evidence.items():
            evidence_html += f"<li><code>{html.escape(str(k))}</code>: <code>{html.escape(str(v))}</code></li>"
        evidence_html += "</ul></div>"

    # Format remediation
    remediation_html = ""
    if show_remediation and finding.remediation:
        # Convert newlines to <br> for simple formatting
        fmt_rem = html.escape(finding.remediation).replace('\n', '<br>')
        # Make bold markdown **text** work in HTML
        fmt_rem = fmt_rem.replace('**', '<strong>').replace('**', '</strong>')
        # This is a hacky bold parser; for a true client report we'd use a markdown lib
        # but we want zero dependencies right now.
        # Let's do a simple fix: if it has **, we alternate open/close tags.
        # Actually, let's just replace pairs.
        parts = fmt_rem.split('<strong>')
        fixed_rem = parts[0]
        for i in range(1, len(parts)):
            fixed_rem += '<strong>' + parts[i].replace('</strong>', '', 1) + '</strong>'
        # Revert the dumb parser, just do basic bold replacement
        # In a real HTML renderer we'd use a markdown parser. For now, keep it simple:
        simple_rem = html.escape(finding.remediation).replace('\n', '<br>')
        # Bold regex equivalent
        import re
        simple_rem = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', simple_rem)
        
        remediation_html = f"<div class='remediation'><h4>Remediation</h4><p>{simple_rem}</p></div>"

    return f"""
    <div class='finding {severity_class}'>
        <div class='finding-header'>
            <h3>{html.escape(check.name)}</h3>
            <span class='badge {severity_class}'>{check.severity.upper()}</span>
        </div>
        <div class='finding-meta'>
            <strong>Status:</strong> {check.status_word().capitalize()} | 
            <strong>Category:</strong> {html.escape(check.category)} | 
            <strong>Target:</strong> {html.escape(check.target)}
        </div>
        <p class='finding-detail'>{html.escape(check.detail)}</p>
        {evidence_html}
        {remediation_html}
    </div>
    """


