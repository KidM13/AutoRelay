"""
AutoRelay — Markdown report renderer.

Takes a FindingsDocument and renders it as a clean, client-facing
Markdown document.
"""

from __future__ import annotations

from .findings import FindingsDocument, Finding


def render_markdown(doc: FindingsDocument) -> str:
    """Render the findings document to Markdown."""
    lines: list[str] = []

    # --- Cover Page / Header ---
    lines.append(f"# NTLM Relay Preflight Assessment")
    lines.append(f"**Target:** `{doc.target}`")
    lines.append(f"**Profile:** `{doc.profile_name}`")
    lines.append(f"**Generated:** {doc.generated_at}")
    lines.append("")
    lines.append("---")
    lines.append("")

    # --- Executive Summary ---
    lines.append("## Executive Summary")
    lines.append("")
    lines.append(doc.summary_text)
    lines.append("")

    # Summary counts
    lines.append("| Status | Count |")
    lines.append("|---|---|")
    lines.append(f"| Blockers | {len(doc.blockers)} |")
    lines.append(f"| Warnings | {len(doc.warnings)} |")
    lines.append(f"| Unknowns | {len(doc.unknowns)} |")
    lines.append(f"| Passed   | {len(doc.info)} |")
    lines.append("")

    # --- Blockers (if any) ---
    if doc.blockers:
        lines.append("## Critical Blockers")
        lines.append("")
        lines.append("The following findings actively prevent the NTLM relay attack from succeeding:")
        lines.append("")
        for finding in doc.blockers:
            _render_finding(lines, finding, level=3)

    # --- Warnings (if any) ---
    if doc.warnings:
        lines.append("## Warnings")
        lines.append("")
        lines.append("The following findings require attention but do not immediately block the attack:")
        lines.append("")
        for finding in doc.warnings:
            _render_finding(lines, finding, level=3)

    # --- Unknowns (if any) ---
    if doc.unknowns:
        lines.append("## Inconclusive Findings")
        lines.append("")
        lines.append("The tool could not determine the state of the following checks. This is common on hardened systems where anonymous probing is restricted.")
        lines.append("")
        for finding in doc.unknowns:
            _render_finding(lines, finding, level=3)

    # --- Passed / Info ---
    if doc.info:
        lines.append("## Passed Checks")
        lines.append("")
        lines.append("The following checks passed or are informational:")
        lines.append("")
        for finding in doc.info:
            _render_finding(lines, finding, level=3, show_remediation=False)

    lines.append("---")
    lines.append("*Report generated by AutoRelay. For authorized security assessment only.*")
    lines.append("")

    return "\n".join(lines)


def _render_finding(lines: list[str], finding: Finding, level: int = 3, show_remediation: bool = True) -> None:
    """Render a single finding block."""
    check = finding.check
    h = "#" * level

    # Heading (use check name, strip the host if it's in the name to keep it clean)
    display_name = check.name
    lines.append(f"{h} {display_name}")
    lines.append("")
    
    # Details
    lines.append(f"- **Target:** `{check.target}`")
    lines.append(f"- **Category:** {check.category}")
    lines.append(f"- **Severity:** {check.severity.capitalize()}")
    lines.append(f"- **Status:** {check.status_word().capitalize()}")
    lines.append(f"- **Detail:** {check.detail}")
    lines.append("")

    # Evidence
    if check.evidence:
        lines.append("**Evidence:**")
        for k, v in check.evidence.items():
            lines.append(f"- `{k}`: `{v}`")
        lines.append("")

    # Remediation
    if show_remediation and finding.remediation:
        lines.append("**Remediation:**")
        lines.append("")
        lines.append(finding.remediation)
        lines.append("")

    lines.append("")
